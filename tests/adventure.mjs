import {TREE_SPECIES,ROOM_OBJECTS,HOUSE_ROOMS,availableActions,completeWorldAction,performRoomAction,hasBowl,nodeAvailable} from '../js/world-actions.js';
import assert from 'node:assert/strict';
import {WORLD_SIZE,WORLD_NODES,WORLD_NPCS,WORLD_DECOR,isWalkable,findPath} from '../js/adventure-world.js';
import {TOOL_RULES,toolUses,pickTool,syncTools,wearTool,gatheringPlan,canGather,applyHarvest} from '../js/adventure-rules.js';

assert.equal(WORLD_SIZE.width,30);
assert.equal(WORLD_SIZE.height,22);
assert.equal(isWalkable(9,10),true,'spawn remains free');
assert.equal(isWalkable(15,10,false),false,'bridge closed');
assert.equal(isWalkable(15,10,true),true,'bridge open');
assert.equal(isWalkable(15,9,true),false,'other river blocked');
assert.equal(isWalkable(0,0),false,'border blocked');
assert.equal(findPath({x:9,y:10},{x:22,y:10},false).length,0,'cannot cross before bridge');
assert.ok(findPath({x:9,y:10},{x:22,y:10},true).length>0,'can cross after bridge');
assert.equal(findPath({x:9,y:10},{x:15,y:12},true).length,0,'no swimming across river');
const ids=new Set([...WORLD_NODES,...WORLD_NPCS].map(e=>e.id));
assert.equal(ids.size,WORLD_NODES.length+WORLD_NPCS.length,'unique NPC and node IDs');
assert.ok(WORLD_DECOR.length>0,'scenery trees populated');
for(const node of WORLD_NODES){
  assert.equal(isWalkable(node.x,node.y,true),node.type==='plant_fiber','trees and rocks block walking; low plants do not');
  assert.ok([[0,1],[0,-1],[1,0],[-1,0]].some(([dx,dy])=>isWalkable(node.x+dx,node.y+dy,true)),'resource approach '+node.id);
}
for(const tree of WORLD_DECOR)assert.equal(isWalkable(tree.x,tree.y,true),false,'decorative tree solid '+tree.id);
for(const npc of WORLD_NPCS)assert.equal(isWalkable(npc.x,npc.y,true),true,'NPC home has walkable terrain');
for(const kind of ['wood','stone','plant_fiber'])assert.ok(WORLD_NODES.filter(n=>n.type===kind).length>=3,'available resource '+kind);
const state={stock:{stone_axe:1,iron_axe:1,stone_pickaxe:1,iron_pickaxe:1},toolDurability:{},discovered:{},xp:0,adventure:{gathered:{}}};
assert.equal(toolUses('stone_axe'),10);
assert.equal(toolUses('iron_axe'),100);
assert.equal(toolUses('stone_pickaxe'),10);
assert.equal(toolUses('iron_pickaxe'),100);
assert.equal(pickTool(state,'wood'),'iron_axe','higher tier first');
assert.equal(gatheringPlan(state,'wood').ms,650,'metal is faster');
assert.equal(gatheringPlan({stock:{}},'wood').ms,6000,'hand harvest is slow');
for(let i=0;i<99;i++)assert.equal(wearTool(state,'iron_axe').broken,false);
assert.equal(state.stock.iron_axe,1,'tool is reusable');
const result100=wearTool(state,'iron_axe');
assert.equal(result100.broken,true,'metal axe breaks at 100');
assert.equal(state.stock.iron_axe,0);
assert.equal(pickTool(state,'wood'),'stone_axe','fallback to stone axe');
const cloned=structuredClone(state);
syncTools(cloned);
assert.equal(cloned.toolDurability.stone_axe[0],10,'tool state survives save/clone');
const resource=WORLD_NODES.find(n=>n.type==='wood');
const now=Date.now();
assert.equal(isWalkable(resource.x,resource.y,true),false);
assert.equal(applyHarvest(state,resource,now).ok,true,'explicit harvest works');
assert.equal(state.stock.wood,resource.qty,'harvest grants exact quantity');
assert.equal(state.toolDurability.stone_axe[0],9,'harvest wears the stone axe once');
assert.equal(canGather(state,resource,now+100),false,'immediate repeated harvest prevented');
assert.equal(applyHarvest(state,resource,now+100).ok,false);
assert.equal(isWalkable(resource.x,resource.y,true,state.adventure.gathered,now+100),true,'tree stump becomes walkable after harvest');
assert.equal(canGather(state,resource,now+300001),true,'tree respawns after delay');
for(let i=0;i<9;i++)wearTool(state,'stone_axe');
assert.equal(state.stock.stone_axe,0,'stone axe breaks after ten total uses');
assert.equal(gatheringPlan(state,'wood').tool,null,'without axe can still work by hand');
assert.equal(Object.keys(TOOL_RULES).length>=6,true,'multiple tool tiers exist');
console.log('Crafterra 0.4: walkability, pathways, gathering and durability OK');


assert.equal(TREE_SPECIES.pine.label,'Pino');
assert.equal(TREE_SPECIES.oak.label,'Roble');
assert.ok(WORLD_DECOR.every(t=>t.kind==='node'&&t.type==='wood'),'no decorative trees');
assert.equal(isWalkable(6,7,true),false,'first house has a solid footprint');
assert.equal(isWalkable(21,7,true),false,'second house has a solid footprint');
assert.ok(Object.keys(HOUSE_ROOMS).length===2,'two playable houses');
assert.ok(ROOM_OBJECTS.house_mara.some(x=>x.id==='bed'));
assert.ok(ROOM_OBJECTS.house_mara.some(x=>x.id==='pantry'));
assert.ok(ROOM_OBJECTS.house_lia.some(x=>x.id==='sawmill'));
assert.ok(ROOM_OBJECTS.house_lia.some(x=>x.id==='repair'));
for(const species of ['pine','oak']){
  const tree={id:'test_'+species,type:'wood',species};
  const a={stock:{},discovered:{},xp:0,toolDurability:{},adventure:{gathered:{}}};
  const opts=availableActions(a,tree);
  assert.equal(opts.length,2);
  assert.equal(opts[0].enabled,false,'chopping requires an axe');
  assert.equal(opts[1].enabled,true,'beating always possible');
  assert.equal(completeWorldAction(a,tree,'chop').ok,false);
  assert.equal(completeWorldAction(a,tree,'hit').ok,true);
  assert.ok(a.stock.rough_wood>=1,'beating yields rough wood');
  assert.equal(a.stock.wood||0,0,'beating does not yield refined wood');
  assert.equal(completeWorldAction(a,tree,'hit').ok,false,'a chopped tree does not give infinite wood immediately');
  const b={stock:{stone_axe:1},discovered:{},xp:0,toolDurability:{},adventure:{gathered:{}}};
  assert.equal(availableActions(b,tree)[0].enabled,true,'axe can chop');
  const cut=completeWorldAction(b,tree,'chop');
  assert.equal(cut.ok,true);
  assert.equal(b.stock.wood,TREE_SPECIES[species].wood);
  assert.equal(b.toolDurability.stone_axe[0],9);
}
const river={id:'river_demo',type:'water',x:14,y:8,qty:1};
const waterState={stock:{},discovered:{},adventure:{gathered:{}}};
assert.equal(hasBowl(waterState),false);
assert.equal(availableActions(waterState,river)[0].enabled,false);
assert.equal(completeWorldAction(waterState,river,'fill').ok,false);
waterState.stock.wood_bowl=1;
assert.equal(completeWorldAction(waterState,river,'fill').ok,true,'bowl permits river water');
assert.equal(waterState.stock.wood_bowl,1,'bowl not consumed');
assert.equal(waterState.stock.water,1);
assert.equal(completeWorldAction(waterState,river,'fill').ok,true,'river is renewable');
const ore={id:'deposit_iron',type:'iron',qty:2};
const mineState={stock:{},discovered:{},adventure:{gathered:{}}};
assert.equal(availableActions(mineState,ore)[0].enabled,false,'ore requires pickaxe');
mineState.stock.stone_pickaxe=1;
assert.equal(completeWorldAction(mineState,ore,'mine').ok,true,'mine with stone pickaxe');
assert.equal(mineState.stock.iron,2);
const quartz={id:'deposit_quartz',type:'quartz',qty:1};
assert.equal(availableActions(mineState,quartz)[0].enabled,false,'quartz needs iron pickaxe');
mineState.stock.iron_pickaxe=1;
assert.equal(completeWorldAction(mineState,quartz,'mine').ok,true);
const home={stock:{rough_wood:2,raw_meat:1,wood:2,stone_axe:1,stone:2},discovered:{},toolDurability:{stone_axe:[5]},adventure:{rooms:{},gathered:{}}};
