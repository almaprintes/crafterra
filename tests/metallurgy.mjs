import assert from 'node:assert/strict';
import {WORLD_WORKSTATIONS,WORLD_NODES,isWalkable,findPath} from '../js/adventure-world.js';
import {stationOptions,runStationProcess,heatOf,FUEL_HEAT,MAX_FIRE_HEAT,STATION_PROCESSES} from '../js/material-economy.js';
import {availableActions,completeWorldAction} from '../js/world-actions.js';
import {pickTool,toolCharge} from '../js/adventure-rules.js';
import {ITEMS,RECIPES} from '../js/data.js';

const state=(stock={})=>({stock:{...stock},adventure:{gathered:{},fires:{}},discovered:{},crafted:{},
 toolDurability:{},xp:0});
const findProcess=(s,station,id)=>stationOptions(s,station,'village_foundry').find(x=>x.id===id);
assert.equal(WORLD_WORKSTATIONS.length,2);
assert.deepEqual(new Set(WORLD_WORKSTATIONS.map(w=>w.station)),new Set(['stonework','foundry']));
for(const w of WORLD_WORKSTATIONS){
 assert.equal(isWalkable(w.x,w.y,false),false,'real workstations occupy terrain');
 assert.equal(WORLD_NODES.some(n=>n.x===w.x&&n.y===w.y),false,'not overlapping resource');
 const neighbors=[[1,0],[0,1],[-1,0],[0,-1]].map(([dx,dy])=>({x:w.x+dx,y:w.y+dy}));
 assert.ok(neighbors.some(n=>isWalkable(n.x,n.y,false)&&findPath({x:9,y:10},n,false).length>0),'station approachable before bridge: '+w.id);
}
for(const [ore,prepared] of [['iron','iron_concentrate'],['copper','copper_concentrate'],
 ['tin','tin_concentrate'],['silver','silver_concentrate'],['gold','gold_concentrate']]){
 assert.ok(ITEMS.some(i=>i.id===ore),'raw ore in catalog');
 assert.ok(ITEMS.some(i=>i.id===prepared),'processed ore in catalog');
 assert.ok(RECIPES.some(r=>r.a===ore&&r.b===ore&&r.result===prepared),'catalog supports the same ore preparation');
 const s=state({[ore]:2});
 assert.equal(runStationProcess(s,'stonework','prep_'+ore).ok,true,'ore preparation '+ore);
 assert.equal(s.stock[ore],0);
 assert.equal(s.stock[prepared],1);
 assert.equal(s.crafted[prepared],1,'process contributes to crafting record');
 assert.ok(STATION_PROCESSES['prep_'+ore].ms>1000,'ore preparation has duration');
}
const s=state({stone:8,handle:4,rope:2,stone_hammer:1,charcoal:6});
const stonePrep=findProcess(s,'stonework','cut_stone_hand');
assert.equal(stonePrep.enabled,true);
assert.equal(runStationProcess(s,'stonework','cut_stone_hand').ok,true);
assert.equal(s.stock.cut_stone,1);
assert.equal(s.stock.stone,6);
assert.equal(runStationProcess(s,'stonework','make_stone_pickaxe').ok,true,'build a basic pickaxe');
assert.equal(s.stock.stone_pickaxe,1);
assert.equal(toolCharge(s,'stone_pickaxe'),10,'new stone pickaxe starts fully charged');
const ironNode=WORLD_NODES.find(n=>n.type==='iron');
assert.equal(availableActions(state(),ironNode)[0].enabled,false,'cannot mine without a pick');
const mine=availableActions(s,ironNode)[0];
assert.equal(mine.enabled,true);
assert.equal(completeWorldAction(s,ironNode,'mine',1_000_000).ok,true,'mine from a specific vein');
assert.equal(s.stock.iron,2);
assert.equal(toolCharge(s,'stone_pickaxe'),9,'mining wears pickaxe');
assert.equal(completeWorldAction(s,ironNode,'mine',1_000_001).ok,false,'vein cooldown');
assert.equal(runStationProcess(s,'stonework','prep_iron').ok,true,'prepare iron ore');
assert.equal(s.stock.iron_concentrate,1);
assert.equal(runStationProcess(s,'fire','smelt_iron','valley').ok,false,'campfire not a foundry');
assert.equal(findProcess(s,'foundry','smelt_iron').enabled,false,'cold furnace blocks smelting');
assert.equal(runStationProcess(s,'foundry','smelt_iron','village_foundry').ok,false);
assert.equal(runStationProcess(s,'foundry','fuel_charcoal','village_foundry').ok,true);
assert.equal(heatOf(s,'village_foundry'),FUEL_HEAT.charcoal);
assert.equal(findProcess(s,'foundry','smelt_iron').enabled,false,'single charcoal insufficient for iron');
assert.equal(runStationProcess(s,'foundry','fuel_charcoal','village_foundry').ok,true);
assert.equal(runStationProcess(s,'foundry','smelt_iron','village_foundry').ok,true);
assert.equal(s.stock.iron_concentrate,0);
assert.equal(s.stock.iron_ingot,1);
assert.equal(s.stock.stone_hammer,1);
assert.equal(runStationProcess(s,'foundry','forge_iron_hammer','village_foundry').ok,true,'first metal hammer uses stone hammer');
assert.equal(s.stock.iron_hammer,1);
assert.equal(toolCharge(s,'iron_hammer'),100,'forged tool has 100 charges');
assert.equal(toolCharge(s,'stone_hammer'),9,'stone hammer preserved, worn once');
const forgeAxe=(id,oreTime)=>{
 s.stock.iron=(s.stock.iron||0)+2; // Another vein or a later respawn
 assert.equal(runStationProcess(s,'stonework','prep_iron').ok,true);
 if(heatOf(s,'village_foundry')<8)assert.equal(runStationProcess(s,'foundry','fuel_charcoal','village_foundry').ok,true);
 assert.equal(runStationProcess(s,'foundry','smelt_iron','village_foundry').ok,true);
 if(heatOf(s,'village_foundry')<4)assert.equal(runStationProcess(s,'foundry','fuel_charcoal','village_foundry').ok,true);
 assert.equal(runStationProcess(s,'foundry',id,'village_foundry').ok,true);
};
forgeAxe('forge_iron_axe');
assert.equal(s.stock.iron_axe,1);
assert.equal(toolCharge(s,'iron_axe'),100,'iron axe is durable');
assert.equal(toolCharge(s,'iron_hammer'),99,'forge uses hammer once without destroying it');
forgeAxe('forge_iron_pickaxe');
assert.equal(s.stock.iron_pickaxe,1);
assert.equal(toolCharge(s,'iron_pickaxe'),100);
assert.equal(pickTool(s,'stone'),'iron_pickaxe','advanced pick automatically preferred');
const quartz=WORLD_NODES.find(n=>n.type==='quartz');
assert.equal(availableActions(s,quartz)[0].enabled,true,'advanced minerals now unlock');
assert.equal(completeWorldAction(s,quartz,'mine',1_200_000).ok,true);
assert.equal(toolCharge(s,'iron_pickaxe'),99);
assert.equal(runStationProcess(s,'foundry','smelt_iron','village_foundry').ok,false,'cannot materialize extra ingots');
assert.ok(heatOf(s,'village_foundry')<=MAX_FIRE_HEAT);
const saved=structuredClone(s);
assert.equal(saved.adventure.fires.village_foundry,heatOf(s,'village_foundry'),'fire persists');
assert.equal(saved.toolDurability.iron_pickaxe[0],99,'durability persists');
const alloy=state({copper_ingot:1,tin_ingot:1,iron_ingot:1,coal:1,charcoal:4});
assert.equal(runStationProcess(alloy,'foundry','bronze_alloy','village_foundry').ok,false,'alloy needs heat');
assert.equal(runStationProcess(alloy,'foundry','fuel_charcoal','village_foundry').ok,true);
assert.equal(runStationProcess(alloy,'foundry','bronze_alloy','village_foundry').ok,true);
assert.equal(alloy.stock.bronze,1);
assert.equal(alloy.stock.copper_ingot,0);
assert.equal(alloy.stock.tin_ingot,0);
assert.equal(runStationProcess(alloy,'foundry','fuel_charcoal','village_foundry').ok,true);
assert.equal(runStationProcess(alloy,'foundry','fuel_charcoal','village_foundry').ok,true);
assert.equal(runStationProcess(alloy,'foundry','steel_alloy','village_foundry').ok,true);
assert.equal(alloy.stock.steel,1);
assert.equal(alloy.stock.coal,0,'coal consumed as reducing ingredient for steel');
const high=state({silver_concentrate:1,gold_concentrate:1,charcoal:4});
assert.equal(runStationProcess(high,'foundry','fuel_charcoal','village_foundry').ok,true);
assert.equal(runStationProcess(high,'foundry','fuel_charcoal','village_foundry').ok,true);
assert.equal(runStationProcess(high,'foundry','smelt_silver','village_foundry').ok,true);
assert.equal(runStationProcess(high,'foundry','fuel_charcoal','village_foundry').ok,true);
assert.equal(runStationProcess(high,'foundry','smelt_gold','village_foundry').ok,true);
assert.equal(high.stock.silver_ingot,1);
assert.equal(high.stock.gold_ingot,1);
console.log('Metalurgia 0.7: piedra → pico → veta → concentrado → horno → lingote → forja → herramienta; aleaciones OK');
